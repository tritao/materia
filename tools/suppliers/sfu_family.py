#!/usr/bin/env python3
"""Drawing-backed SFU nuts and DSG housings. Thread depths/root remain explicit design inputs."""
import argparse
import json
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[2]
MANIFEST=Path(__file__).with_name('sfu-reference.json')
TARGET=ROOT/'machinekit/haxe/src/machinekit/motion/SfuFamilyData.hx'
def models():return json.loads(MANIFEST.read_text())['models']
def generated():
    lines=['package machinekit.motion;',
      'typedef SfuNutReference = {model:String,diameter:Float,pitch:Float,pilot:Float,barrel:Float,flange:Float,pcd:Float,hole:Float,length:Float,offset:Float,thickness:Float,flats:Float,mount:String};',
      'typedef DsgHousingReference = {model:String,bore:Float,width:Float,height:Float,shaftHeight:Float,chamfer:Float,length:Float,firstHole:Float,holePitchZ:Float,holePitchX:Float,baseThread:String,flangePcd:Float,flangeThread:String};',
      '// Generated by tools/suppliers/sfu_family.py --emit from pinned Vallder tables.',
      'class SfuFamilyData {']
    for kind,pid,typ in [('nut',3061,'SfuNutReference'),('housing',3097,'DsgHousingReference')]:
        rows=[m for m in models() if m['parent_id']==pid]
        lines.append(' public static function '+kind+'Models():Array<String> return '+json.dumps([m['model'] for m in rows])+';')
        lines.append(' public static function '+kind+'(model:String):'+typ+' return switch model {')
        for m in rows:
            r=m['table_row']
            if kind=='nut':
                keys=['diameter','pitch','pilot','barrel','flange','pcd','hole','length','offset','thickness','flats'];indices=[1,2,6,7,8,9,10,11,12,13,15]
                v={k:float(r[i]) for k,i in zip(keys,indices)};v['mount']='M5' if v['diameter']==16 else 'M6'
            else:
                keys=['bore','width','height','shaftHeight','chamfer','length','firstHole','holePitchZ','holePitchX','flangePcd'];indices=[2,3,4,5,6,7,8,9,10,12]
                v={k:float(r[i]) for k,i in zip(keys,indices)};v.update(baseThread=r[11],flangeThread=r[13])
            v['model']=m['model'];obj=re.sub(r'([,{]\s*)"([A-Za-z][A-Za-z0-9]*)":',r'\1\2:',json.dumps(v))
            lines.append('  case '+json.dumps(m['model'])+': '+obj+';')
        lines+=['  default: throw "Unknown SFU family model: "+model;',' };']
    return '\n'.join(lines+['}'])+'\n'
def build(catalog):
    recipes=[]
    for m in models():
        p=next(p for p in catalog['products'] if p['supplier_product_id']==m['parent_id'])
        if [r for t in p['specification_tables'] for r in t if r and r[0]==m['table_row'][0]]!=[m['table_row']]:raise ValueError('SFU table changed: '+m['model'])
        v=[v for v in catalog['variants'] if v['parent_id']==m['parent_id'] and v['sku']==m['sku']]
        if len(v)!=1 or v[0]['supplier_product_id']!=m['variant_id']:raise ValueError('SFU variant changed: '+m['model'])
        nut=m['parent_id']==3061
        recipes.append(dict(supplier_id='vallder',sku=m['sku'],supplier_product_id=m['variant_id'],parent_id=m['parent_id'],
            type_id='machinekit.motion.sfu-nut' if nut else 'machinekit.motion.dsg-nut-housing',values={'model':m['model']},
            required_inputs=['raceRootDiameter'] if nut else ['baseThreadDepth','flangeThreadDepth'],geometry_source='generator',
            compatibility='supplier_assumed',source_url=p['url'],limits=['Catalogue assembly dimensions; no preload/load/material qualification',
                'Race root is an explicit engineering assumption' if nut else 'Blind thread depths are not stated; explicit design inputs, not a machining request']))
    stock=next(p for p in catalog['products'] if p['supplier_product_id']==3000)
    for model,sku in [('SFU2005','1033003'),('SFU2010','1033004'),('SFU2505','1033005'),('SFU2510','1033006')]:
        rows=[r for t in stock['specification_tables'] for r in t if r and r[0].replace(' ','')==model]
        if len(rows)!=1 or rows[0][1]!=sku or rows[0][2:4]!=[model[-2:].lstrip('0'),model[3:5]]:
            raise ValueError('Stock SFU evidence changed: '+model)
        v=[v for v in catalog['variants'] if v['parent_id']==3000 and v['sku']==sku]
        if len(v)!=1:raise ValueError('Stock SFU variant changed: '+model)
        recipes.append(dict(supplier_id='vallder',sku=sku,supplier_product_id=v[0]['supplier_product_id'],parent_id=3000,
            type_id='machinekit.motion.sfu-drawing-screw',values={'model':model},required_inputs=['length','raceRootDiameter'],
            geometry_source='generator',compatibility='supplier_assumed',source_url=stock['url'],custom_end_machining=False,
            sourcing_option='published_standard_end_profile',
            limits=['Select the published standard end option when ordering stock by length; per-metre price is not a piece quote',
                    'Race root and lock-thread root envelopes are engineering assumptions; small end fillets/chamfers omitted']))
    return {'schema_version':1,'recipes':recipes}
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--emit',action='store_true');p.add_argument('--check',action='store_true');a=p.parse_args()
    if a.emit:TARGET.write_text(generated())
    if a.check and TARGET.read_text()!=generated():raise SystemExit('SFU generated data is stale')
