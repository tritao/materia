#!/usr/bin/env python3
"""Validate reviewed HZMotion interfaces, pin source PDFs, and generate runtime data.

STEP links currently require supplier login. No credentials are stored here and
no failed download is represented as a supplier CAD asset.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parents[2]
REFERENCE = Path(__file__).with_name('hzmotion-reference.json')
TARGET = ROOT / 'machinekit/haxe/src/machinekit/assembly/HzMotionData.hx'


def validate(data):
    if data['schemaVersion'] != 1:
        raise ValueError('Unknown HZMotion reference schema')
    models = set()
    for p in data['parts']:
        if p['model'] in models:
            raise ValueError('Duplicate HZMotion part')
        models.add(p['model'])
        if p['source'] not in data['sources'] or not 1 <= p['page'] <= data['sources'][p['source']]['pages']:
            raise ValueError('Invalid drawing page')
        for field in ['length', 'width', 'rearWidth', 'rearHeight', 'shaftBore']:
            if not isinstance(p[field], (float, int)) or not math.isfinite(p[field]) or p[field] <= 0:
                raise ValueError(f'Invalid {field} for {p["model"]}')
        if p['kind'] in ['mount', 'adapter'] and not (p['pilot'] > 0 and p['pcd'] > p['pilot']):
            raise ValueError('Invalid motor interface')
        if p['massKg'] is not None and p['massKg'] <= 0:
            raise ValueError('Invalid declared mass')
    keys = [(r['family'], r['motorInterface'], r['support']) for r in data['coverage']]
    if len(keys) != len(set(keys)) or {r[0] for r in keys} != {'A', 'B', 'C', 'H', 'L', 'KK'}:
        raise ValueError('Invalid coverage index')
    # A bearing diameter is never a claim of full screw-end compatibility.
    if next(p for p in data['parts'] if p['model'] == 'BF12')['shaftBore'] != 10:
        raise ValueError('BF12 floating journal must be 10 mm, not 12 mm')
    return data


RUNTIME_FIELDS = "model kind family page source integrated face pilot pcd thread threadDepth pilotDepth length shaftHeight width flange rearStart rearEnd rearWidth rearHeight shaftBore shoulderZ massKg baseHoles bearing bearingArrangement maxAxialLoadKgf oppositeSupport endProfile geometryBasis drawingRevision".split()


def literal(value):
    if isinstance(value, dict):
        return "{" + ",".join(k + ":" + literal(v) for k, v in value.items()) + "}"
    if isinstance(value, list):
        return "[" + ",".join(literal(v) for v in value) + "]"
    return json.dumps(value, ensure_ascii=True)


def render(data):
    # Typed literals avoid runtime Dynamic->anonymous-structure coercion and return
    # fresh records, so catalog consumers cannot mutate the pinned source table.
    parts = [{k: p[k] for k in RUNTIME_FIELDS} for p in data['parts']]
    return ('package machinekit.assembly;\n\n'
            'import machinekit.assembly.HzMotionCatalog.HzMotionSpec;\n'
            'import machinekit.assembly.HzMotionCatalog.HzMotionCoverage;\n'
            '// Generated by tools/suppliers/hzmotion.py --write-haxe; review hzmotion-reference.json.\n'
            'class HzMotionData {\n'
            ' public static function revision():String return ' + literal(data['revision']) + ';\n'
            ' public static function parts():Array<HzMotionSpec> return [\n  '
            + ',\n  '.join(literal(p) for p in parts) + '\n ];\n'
            ' public static function coverage():Array<HzMotionCoverage> return [\n  '
            + ',\n  '.join(literal(p) for p in data['coverage']) + '\n ];\n'
            ' public static function discrepancies():Array<String> return ' + literal(data['discrepancies']) + ';\n'
            '}\n')


def source_files(data, directory, offline):
    raw = directory / 'raw'
    raw.mkdir(parents=True, exist_ok=True)
    for source in data['sources'].values():
        path = raw / source['url'].rsplit('/', 1)[-1]
        if not path.exists():
            if offline:
                raise ValueError(f'Missing pinned source {path}')
            request = urllib.request.Request(source['url'], headers={'User-Agent': 'MateriaSupplierCatalog/1.0'})
            content = urllib.request.urlopen(request, timeout=60).read()
            if hashlib.sha256(content).hexdigest() != source['sha256']:
                raise ValueError('Supplier source changed; review a new revision before importing')
            path.write_bytes(content)
        if hashlib.sha256(path.read_bytes()).hexdigest() != source['sha256']:
            raise ValueError(f'Pinned source hash mismatch: {path}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'build/suppliers/hzmotion')
    parser.add_argument('--offline', action='store_true')
    parser.add_argument('--write-haxe', action='store_true')
    parser.add_argument('--check', action='store_true', help='Check data and generated runtime without network')
    args = parser.parse_args()
    data = validate(json.loads(REFERENCE.read_text()))
    generated = render(data)
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != generated:
            raise ValueError('HZMotion runtime differs; regenerate explicitly with --write-haxe')
    else:
        source_files(data, args.output, args.offline)
        (args.output / 'catalog.json').write_text(json.dumps(data, indent=2) + '\n')
    if args.write_haxe:
        TARGET.write_text(generated)
    print(f'HZMotion: {len(data["coverage"])} coverage records; {len(data["parts"])} drawing-based components')


if __name__ == '__main__':
    main()
