#!/usr/bin/env python3
"""Pinned HG reference family: exact rail sections and detailed carriage CAD.

Prepare local CAD with --prepare. --emit updates the generated, offline Haxe data.
Supplier bindings require exact table evidence and actual SKU variants.
"""
import argparse
import hashlib
import json
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = Path(__file__).with_name('hg-reference.json')
TARGET = ROOT / 'machinekit/haxe/src/machinekit/motion/HgReferenceData.hx'


def models():
    return json.loads(MANIFEST.read_text())['models']


def build(catalog):
    recipes = []
    for model in models():
        parent = next(p for p in catalog['products'] if p['supplier_product_id'] == model['parent_id'])
        rows = [r for t in parent['specification_tables'] for r in t if len(r) == len(model['table_row']) and r[0] == model['table_row'][0]]
        if rows != [model['table_row']]:
            raise ValueError('HG table changed; review ' + model['model'])
        # Table-only sizes are supported by the generic reference, never invented supplier offers.
        matching = [v for v in catalog['variants'] if v['parent_id'] == model['parent_id'] and
                    (v['sku'] == model['table_row'][-1] if model['parent_id'] == 39276 else any(
                        a['value'].replace('_', '').upper() == model['model'] for a in v['option_attributes']))]
        if len(matching) > 1:
            raise ValueError('Ambiguous HG variant: ' + model['model'])
        for variant in matching:
            rail = model['parent_id'] == 39276
            recipes.append(dict(supplier_id='vallder', sku=variant['sku'], supplier_product_id=variant['supplier_product_id'],
                parent_id=model['parent_id'], type_id='machinekit.motion.hg-rail' if rail else 'machinekit.motion.hg-block-reference',
                values={'model':model['model']}, required_inputs=['length'] if rail else [],
                geometry_source='generator' if rail else 'reference_cad', compatibility='supplier_assumed',
                source_url=parent['url'], reference_sha256=model['sha256'],
                limits=['Load/preload and material are not qualified', 'Default rail cutting uses the table end margin; cut length requires supplier sourcing'] if rail else
                       ['Pinned HIWIN reference exterior; supplier equivalence remains an assembly check',
                        'HGW thread depth is not specified by the Vallder table'] if model['model'].startswith('HGW') else
                       ['Pinned HIWIN reference exterior; supplier equivalence remains an assembly check']))
    return {'schema_version':1, 'recipes':recipes}


def generated():
    lines=['package machinekit.motion;','','// Generated by tools/suppliers/hg.py --emit from pinned table/CAD evidence.',
           'import machinekit.motion.LinearRailProfile.LinearRailProfileSpec;',
           'class HgReferenceData {']
    all_models=models()
    for name,expr in [('models', lambda m: True), ('rails', lambda m: m['model'].startswith('HGR')), ('blocks', lambda m: not m['model'].startswith('HGR'))]:
        values=[m['model'] for m in all_models if expr(m)]
        lines.append(' public static function '+name+'():Array<String> return '+json.dumps(values)+';')
    for fn,typ,field in [('hash','String','sha256'),('low','Array<Float>','min'),('high','Array<Float>','max'),('section','Array<Array<Float>>','section')]:
        lines.append(' public static function '+fn+'(model:String):'+typ+' return switch model {')
        for m in all_models:
            if field in m:lines.append('  case '+json.dumps(m['model'])+': '+json.dumps(m[field])+';')
        lines+=['  default: throw "Unknown HG reference: "+model;',' };']
    lines.append(' public static function spec(model:String):LinearRailProfileSpec return switch model {')
    for m in all_models:
        n=m['model'];r=m['table_row']
        if n.startswith('HGR'):r=next(x['table_row'] for x in all_models if x['model']==n.replace('HGR','HGH').replace('R','CA'))
        w=n.startswith('HGW');i=0 if not w else 1
        # Row indices shifted by HGW's extra T1 column after T.
        vals=dict(designation=n,family='HG',railWidth=float(r[16+i]),railHeight=float(r[17+i]),
                  blockWidth=float(r[4]),blockHeight=float(r[1]),blockLength=float(r[9]),
                  blockHolePitchB=float(r[7]),blockHolePitchC=float(r[5]),blockMountScrew=r[12].split('x')[0],
                  railHolePitch=float(r[21+i]),railEndMargin=float(r[22+i]),railMountScrew=r[23+i].split('x')[0],
                  staticLoadCapacity=float(r[25+i].replace(',','.'))*1000)
        lines.append('  case '+json.dumps(n)+': '+json.dumps(vals).replace('"designation":','designation:').replace('"family":','family:')+';')
    lines+=['  default: throw "Unknown HG reference: "+model;',' };','}']
    # Haxe accepts quoted structure field names? Use identifiers for all keys.
    import re
    return re.sub(r'([,{]\s*)"([A-Za-z][A-Za-z0-9]*)":',r'\1\2:', '\n'.join(lines)+'\n')


def prepare(output):
    output.mkdir(parents=True,exist_ok=True)
    for m in models():
        path=output/(m['model']+'.step')
        data=path.read_bytes() if path.exists() else urllib.request.urlopen(m['cad_url'],timeout=60).read()
        if hashlib.sha256(data).hexdigest()!=m['sha256'] or not data.startswith(b'ISO-10303-21;'):
            raise ValueError('Unreviewed HG reference: '+m['model'])
        if not path.exists():path.write_bytes(data)


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--emit',action='store_true');parser.add_argument('--check',action='store_true')
    parser.add_argument('--prepare',type=Path)
    args=parser.parse_args()
    if args.prepare:prepare(args.prepare)
    if args.emit:TARGET.write_text(generated())
    if args.check and TARGET.read_text()!=generated():raise SystemExit('HG generated data is stale')
