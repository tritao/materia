#!/usr/bin/env python3
"""Pinned BK/BF/FK/FF tables and CAD; regenerate Haxe data with --emit."""
import argparse
import json
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[2]
MANIFEST=Path(__file__).with_name('support-reference.json')
TARGET=ROOT/'machinekit/haxe/src/machinekit/motion/VallderSupportData.hx'

def models():return json.loads(MANIFEST.read_text())['models']

def generated():
    rows=models()
    lines=['package machinekit.motion;',
        'typedef ScrewSupportReference = {model:String,sku:String,sha256:String,bore:Float,base:Bool,shaftHeight:Float,width:Float,height:Float,length:Float,pitch:Float,longitudinalPitch:Float,clearance:Float,counterbore:Float};',
        '// Generated by tools/suppliers/supports.py --emit. Mixed materials; bearing included.',
        'class VallderSupportData {',
        'public static function models():Array<String> return '+json.dumps([r['model'] for r in rows if r['model'] not in ('FK17', 'FF17')])+';',
        'public static function get(model:String):ScrewSupportReference return switch model {']
    for r in rows:
        vals={k:v for k,v in r.items() if k not in ['parent_id','variant_id','source_url','table_row']}
        obj=re.sub(r'([,{]\s*)"([A-Za-z][A-Za-z0-9]*)":',r'\1\2:',json.dumps(vals))
        lines.append('case '+json.dumps(r['model'])+': '+obj+';')
    return '\n'.join(lines+['default:throw "Unknown Vallder support: "+model;','};','}'])+'\n'

def build(catalog,library):
    recipes=[]
    for m in models():
        if m["model"] in ("FK17", "FF17"):continue  # Published flange pattern fails the pinned CAD bore probe.
        parent=next(p for p in catalog['products'] if p['supplier_product_id']==m['parent_id'])
        rows=[r for t in parent['specification_tables'] for r in t if r and r[0]==m['table_row'][0]]
        if rows!=[m['table_row']]:raise ValueError('Support table changed: '+m['model'])
        variants=[v for v in catalog['variants'] if v['parent_id']==m['parent_id'] and v['sku']==m['sku']]
        if len(variants)!=1 or variants[0]['supplier_product_id']!=m['variant_id']:
            raise ValueError('Support variant changed: '+m['model'])
        assets=[a for a in library if a['sha256']==m['sha256'] and a['product_id']==m['parent_id'] and m['variant_id'] in a['variant_ids'] and a['usable_geometry']]
        if not assets:continue
        recipes.append(dict(supplier_id='vallder',sku=m['sku'],supplier_product_id=m['variant_id'],parent_id=m['parent_id'],
            type_id='machinekit.motion.vallder-screw-support',values={'model':m['model']},required_inputs=[],geometry_source='supplier_cad',interface_status='cad_mounting_axes_checked',
            compatibility='supplier_assumed',source_url=parent['url'],reference_sha256=m['sha256'],
            limits=['Bearing/hardware already included in CAD and BOM item',
                    'Raw CAD shaft-axis frame; mounting faces and bolt axes follow published table',
                    'Journal diameter is a mating interface; axial seating, preload and load capacity need assembly checks']))
    return {'schema_version':1,'recipes':recipes,'interface_checks':json.loads(MANIFEST.read_text())['interface_checks']}

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--emit',action='store_true');p.add_argument('--check',action='store_true');a=p.parse_args()
    if a.emit:TARGET.write_text(generated())
    if a.check and TARGET.read_text()!=generated():raise SystemExit('Support generated data is stale')
