#!/usr/bin/env python3
"""Reproduce manually inspected raster-graph readings; never infer qualification.

Coordinates refer to original PNGs. Piecewise tick calibration is necessary for
the two schematic large-motor graphs; their tick spacing is not a uniform scale.
Uncertainties are conservative reading allowances, not manufacturer tolerances.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCES = ROOT / "sources/leadshine-curves"
GENERATED = ROOT.parents[1] / "haxe/src/machinekit/motion/LeadshineTorqueCurveData.hx"


def interpolate(anchors, value):
    anchors = sorted(anchors)
    if not anchors[0][0] <= value <= anchors[-1][0]:
        raise ValueError("Pixel outside calibrated range")
    for (x0, y0), (x1, y1) in zip(anchors, anchors[1:]):
        if x0 <= value <= x1:
            return y0 + (y1-y0)*(value-x0)/(x1-x0)
    return anchors[-1][1]


def generate():
    manifest = json.loads((SOURCES/"manifest.json").read_text())
    calibration = [
        {"speedTicks":[[90,0],[199,3000],[271,5000]],
         "torqueTicks":[[221,0],[178.5,4.9],[91.5,14.7]],
         "continuousPixels":[[90,178.5],[199,178.5],[271,202]],
         "intermittentPixels":[[90,91.5],[199,91.5],[271,178]],
         "torqueReadingUncertaintyNm":0.15,"speedReadingUncertaintyRpm":60,
         "matchedDesignation":"ELM2L-1500LA100FT-H MS1AE",
         "status":"matched_page_variant_conditions_unverified"},
        {"speedTicks":[[64,0],[276,1500],[404,3000]],
         "torqueTicks":[[171,0],[126,18.6],[81,31.2],[34,46.5]],
         "continuousPixels":[[64,126],[276,126],[404,147]],
         "intermittentPixels":[[64,34],[276,34],[404,68]],
         "torqueReadingUncertaintyNm":1.0,"speedReadingUncertaintyRpm":30,
         "matchedDesignation":None,"status":"blocked_rating_conflict_and_schematic_axes"},
        {"speedTicks":[[59,0],[272,1500],[404,3000]],
         "torqueTicks":[[176,0],[131,48],[86,96],[39,119]],
         "continuousPixels":[[59,131],[272,131],[404,152]],
         "intermittentPixels":[[59,39],[272,39],[404,74]],
         "torqueReadingUncertaintyNm":2.5,"speedReadingUncertaintyRpm":30,
         "matchedDesignation":None,"status":"blocked_revision_conflict_and_schematic_axes"}
    ]
    curves = []
    for source, cal in zip(manifest["records"],calibration):
        assert hashlib.sha256((SOURCES/source["file"]).read_bytes()).hexdigest() == source["sha256"]
        def points(pixels):
            return [{"rpm":round(interpolate(cal["speedTicks"],x),6),
                     "torqueNm":round(interpolate(cal["torqueTicks"],y),6)} for x,y in pixels]
        curve = {"id":source["file"].removesuffix(".png"),"baseDesignation":source["model"],
                 "matchedDesignation":cal["matchedDesignation"],"pageVariant":source["page_variant"],
                 "source":source["page_url"],"imageSource":source["image_url"],"imageSha256":source["sha256"],
                 "status":cal["status"],"operatingConditionsVerified":False,
                 "intermittentDurationSeconds":None,"review":source["review"],
                 "torqueReadingUncertaintyNm":cal["torqueReadingUncertaintyNm"],
                 "speedReadingUncertaintyRpm":cal["speedReadingUncertaintyRpm"],
                 "continuous":points(cal["continuousPixels"]),"intermittent":points(cal["intermittentPixels"]),
                 "calibration":cal}
        curves.append(curve)
    encoded = json.dumps({"schemaVersion":1,"curves":curves},indent=2)+"\n"
    # Embed source evidence for native/headless builds; no runtime filesystem dependency.
    def haxe_literal(value):
        if isinstance(value,dict):
            return "{"+", ".join(key+":"+haxe_literal(v) for key,v in value.items() if key != "calibration")+"}"
        if isinstance(value,list):
            return "["+", ".join(haxe_literal(v) for v in value)+"]"
        return json.dumps(value)
    literal = haxe_literal(curves)
    haxe = ('package machinekit.motion;\n\n/** Generated by examples/spindle-drive-study/digitize_curves.py. */\n'
            'class LeadshineTorqueCurveData {\n\tpublic static function rows():Array<LeadshineTorqueCurves.LeadshineTorqueCurve>\n'
            '\t\treturn '+literal+';\n}\n')
    return encoded,haxe


def main():
    p = argparse.ArgumentParser(description=__doc__);p.add_argument("--check",action="store_true");args=p.parse_args()
    encoded,haxe=generate()
    for path,text in [(ROOT/"digitized-curves.json",encoded),(GENERATED,haxe)]:
        if args.check:
            if path.read_text()!=text:raise SystemExit(f"Stale generated curve data: {path}")
        else:path.write_text(text)
    print("Three raster curves digitized; only explicit MS1AE variant matched, none qualified")


if __name__=="__main__":main()
