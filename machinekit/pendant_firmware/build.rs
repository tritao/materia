//! Generates the pendant's pin module from the board's pin table, `pendant.pins.json` in the pendant board's folder (pcbkit
//! PLAN W5): the board's circuit wires those nets on those pins, pcbkit's pin check proves the netlist follows the table, and
//! this firmware takes exactly those pins, so the three cannot drift apart. Each assigned pin becomes a field named after its
//! net; a pin that cannot carry the peripheral it is given fails to compile where the field is used.
use std::{env, fs, path::Path};

const TABLE: &str = "../examples/pendant/electronics/pendant/pendant.pins.json";

fn main() {
    println!("cargo:rerun-if-changed={TABLE}");
    let text = fs::read_to_string(TABLE).unwrap_or_else(|e| panic!("{TABLE}: {e}"));
    let doc: serde_json::Value = serde_json::from_str(&text).unwrap_or_else(|e| panic!("{TABLE}: {e}"));
    assert_eq!(doc["schema"], 1, "{TABLE}: only schema 1 is supported");
    let pins = doc["pins"].as_object().unwrap_or_else(|| panic!("{TABLE}: pins must be an object"));
    let (mut fields, mut moves) = (String::new(), String::new());
    for (port, entry) in pins {
        let Some(net) = entry["net"].as_str() else { continue };
        let function = entry["function"].as_str().unwrap_or_else(|| panic!("{TABLE}: {port} has no function"));
        let note = entry.get("note").and_then(|n| n.as_str()).map(|n| format!(": {n}")).unwrap_or_default();
        let name = net.to_lowercase();
        fields += &format!("    /// {port}, {function}{note}\n    pub {name}: Peri<'static, peripherals::{port}>,\n");
        moves += &format!("            {name}: $p.{port},\n");
    }
    let module = format!(
        "// Generated by build.rs from {TABLE}; edit the table, not this file.\n\
         use embassy_stm32::{{peripherals, Peri}};\n\n\
         /// The pendant board's assigned pins, one per net of its pin table.\n\
         #[allow(dead_code)]\n\
         pub struct Pins {{\n{fields}}}\n\n\
         /// Moves the board's pins out of `embassy_stm32::Peripherals`; its other peripherals stay usable.\n\
         macro_rules! take_pins {{\n    ($p:ident) => {{\n        crate::pins::Pins {{\n{moves}        }}\n    }};\n}}\n\
         pub(crate) use take_pins;\n"
    );
    fs::write(Path::new(&env::var("OUT_DIR").unwrap()).join("pins.rs"), module).unwrap();
}
